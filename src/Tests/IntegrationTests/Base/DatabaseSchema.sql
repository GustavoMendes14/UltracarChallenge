-- Schema used by the API repositories, including the constraints and indexes
-- from the local PostgreSQL database. Keep it aligned with schema changes.
CREATE EXTENSION IF NOT EXISTS pg_trgm;

CREATE TABLE parts (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_parts PRIMARY KEY,
    workshop_id bigint NOT NULL,
    code text NOT NULL,
    description text NOT NULL,
    physical_stock integer NOT NULL DEFAULT 0,
    CONSTRAINT ck_parts_id_positive CHECK (id > 0),
    CONSTRAINT ck_parts_workshop_id_positive CHECK (workshop_id > 0),
    CONSTRAINT ck_parts_code_not_blank CHECK (length(btrim(code)) > 0),
    CONSTRAINT ck_parts_description_not_blank CHECK (length(btrim(description)) > 0),
    CONSTRAINT ck_parts_physical_stock_nonnegative CHECK (physical_stock >= 0)
);

CREATE UNIQUE INDEX uq_parts_workshop_id ON parts (workshop_id, id);
CREATE UNIQUE INDEX uq_parts_workshop_code ON parts (workshop_id, code);
CREATE INDEX ix_parts_code_trgm ON parts USING gin (code gin_trgm_ops);
CREATE INDEX ix_parts_description_trgm ON parts USING gin (description gin_trgm_ops);

CREATE TABLE reservations (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_reservations PRIMARY KEY,
    workshop_id bigint NOT NULL,
    service_order_id text NOT NULL,
    user_id bigint NOT NULL,
    status integer NOT NULL DEFAULT 1,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    expires_at timestamptz NOT NULL DEFAULT (statement_timestamp() + interval '30 minutes'),
    CONSTRAINT ck_reservations_id_positive CHECK (id > 0),
    CONSTRAINT ck_reservations_workshop_id_positive CHECK (workshop_id > 0),
    CONSTRAINT ck_reservations_service_order_id_not_blank CHECK (length(btrim(service_order_id)) > 0),
    CONSTRAINT ck_reservations_service_order_id_length CHECK (length(service_order_id) <= 100),
    CONSTRAINT ck_reservations_user_id_positive CHECK (user_id > 0),
    CONSTRAINT ck_reservations_status CHECK (status IN (1, 2, 3, 4)),
    CONSTRAINT ck_reservations_expiration CHECK (expires_at = created_at + interval '30 minutes')
);

CREATE UNIQUE INDEX uq_reservations_workshop_id ON reservations (workshop_id, id);
CREATE INDEX ix_reservations_active_workshop_id ON reservations (workshop_id, id)
    INCLUDE (expires_at) WHERE status = 1;

CREATE TABLE reservation_items (
    id bigint GENERATED BY DEFAULT AS IDENTITY CONSTRAINT pk_reservation_items PRIMARY KEY,
    reservation_id bigint NOT NULL,
    workshop_id bigint NOT NULL,
    part_id bigint NOT NULL,
    quantity integer NOT NULL,
    CONSTRAINT ck_reservation_items_id_positive CHECK (id > 0),
    CONSTRAINT ck_reservation_items_workshop_id_positive CHECK (workshop_id > 0),
    CONSTRAINT ck_reservation_items_quantity_positive CHECK (quantity > 0),
    CONSTRAINT fk_reservation_items_reservation FOREIGN KEY (workshop_id, reservation_id)
        REFERENCES reservations (workshop_id, id) ON DELETE RESTRICT,
    CONSTRAINT fk_reservation_items_part FOREIGN KEY (workshop_id, part_id)
        REFERENCES parts (workshop_id, id) ON DELETE RESTRICT
);

CREATE UNIQUE INDEX uq_reservation_items_workshop_reservation_part
    ON reservation_items (workshop_id, reservation_id, part_id);
CREATE INDEX ix_reservation_items_workshop_part_reservation
    ON reservation_items (workshop_id, part_id, reservation_id) INCLUDE (quantity);

CREATE TABLE reservation_idempotency (
    workshop_id bigint NOT NULL,
    idempotency_key varchar(200) NOT NULL,
    request_hash varchar(64) NOT NULL,
    response_json text,
    created_at timestamptz NOT NULL DEFAULT statement_timestamp(),
    CONSTRAINT pk_reservation_idempotency PRIMARY KEY (workshop_id, idempotency_key),
    CONSTRAINT ck_reservation_idempotency_workshop_id_positive CHECK (workshop_id > 0),
    CONSTRAINT ck_reservation_idempotency_key_not_blank CHECK (length(btrim(idempotency_key)) > 0),
    CONSTRAINT ck_reservation_idempotency_key_length CHECK (length(idempotency_key) <= 200),
    CONSTRAINT ck_reservation_idempotency_request_hash CHECK (request_hash ~ '^[0-9A-Fa-f]{64}$'),
    CONSTRAINT ck_reservation_idempotency_response_json
        CHECK (response_json IS NULL OR jsonb_typeof(response_json::jsonb) = 'object')
);
