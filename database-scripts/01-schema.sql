-- ============================================================
-- Primary keys
--
-- Existing primary keys must use the expected columns.
-- ============================================================

DO $primary_keys$
DECLARE
    target record;
    existing_columns text[];
    column_list text;
BEGIN
    FOR target IN
        SELECT *
        FROM (
            VALUES
                (
                    'parts',
                    'pk_parts',
                    ARRAY['id']::text[]
                ),
                (
                    'reservations',
                    'pk_reservations',
                    ARRAY['id']::text[]
                ),
                (
                    'reservation_items',
                    'pk_reservation_items',
                    ARRAY['id']::text[]
                ),
                (
                    'reservation_idempotency',
                    'pk_reservation_idempotency',
                    ARRAY[
                        'workshop_id',
                        'idempotency_key'
                    ]::text[]
                )
        ) AS definitions(
            table_name,
            constraint_name,
            key_columns
        )
    LOOP
        SELECT array_agg(
            attribute.attname::text
            ORDER BY key_column.ordinal_position
        )
        INTO existing_columns
        FROM pg_constraint constraint_info
        CROSS JOIN LATERAL unnest(
            constraint_info.conkey
        ) WITH ORDINALITY AS key_column(
            attribute_number,
            ordinal_position
        )
        JOIN pg_attribute attribute
          ON attribute.attrelid = constraint_info.conrelid
         AND attribute.attnum = key_column.attribute_number
        WHERE constraint_info.conrelid = to_regclass(
            format('public.%I', target.table_name)
        )
          AND constraint_info.contype = 'p';

        IF existing_columns IS NULL THEN
            SELECT string_agg(
                format('%I', column_name),
                ', '
            )
            INTO column_list
            FROM unnest(
                target.key_columns
            ) AS columns_to_use(column_name);

            EXECUTE format(
                'ALTER TABLE public.%I ADD CONSTRAINT %I PRIMARY KEY (%s)',
                target.table_name,
                target.constraint_name,
                column_list
            );

        ELSIF existing_columns <> target.key_columns THEN
            RAISE EXCEPTION
                'Unexpected primary key on public.%. Expected columns: %. Existing columns: %.',
                target.table_name,
                target.key_columns,
                existing_columns;
        END IF;
    END LOOP;
END;
$primary_keys$;

