-- ============================================================
-- Identity generators
--
-- Preserve existing identity/serial generators.
-- Add identity generation when the ID has no generator/default.
-- Advance sequences only when existing IDs require it.
-- ============================================================

DO $identity_generators$
DECLARE
    target record;
    sequence_name text;
    default_expression text;
    maximum_id bigint;
    sequence_last_value bigint;
    sequence_is_called boolean;
BEGIN
    FOR target IN
        SELECT *
        FROM (
            VALUES
                ('parts'),
                ('reservations'),
                ('reservation_items')
        ) AS definitions(table_name)
    LOOP
        sequence_name := pg_get_serial_sequence(
            format('public.%I', target.table_name),
            'id'
        );

        IF sequence_name IS NULL THEN
            SELECT pg_get_expr(
                default_info.adbin,
                default_info.adrelid
            )
            INTO default_expression
            FROM pg_attribute attribute
            LEFT JOIN pg_attrdef default_info
              ON default_info.adrelid = attribute.attrelid
             AND default_info.adnum = attribute.attnum
            WHERE attribute.attrelid = to_regclass(
                format('public.%I', target.table_name)
            )
              AND attribute.attname = 'id'
              AND NOT attribute.attisdropped;

            IF default_expression IS NOT NULL THEN
                RAISE EXCEPTION
                    'Unexpected ID default on public.%: %',
                    target.table_name,
                    default_expression;
            END IF;

            EXECUTE format(
                'ALTER TABLE public.%I ALTER COLUMN id ADD GENERATED BY DEFAULT AS IDENTITY',
                target.table_name
            );

            sequence_name := pg_get_serial_sequence(
                format('public.%I', target.table_name),
                'id'
            );
        END IF;

        EXECUTE format(
            'SELECT COALESCE(MAX(id), 0)::bigint FROM public.%I',
            target.table_name
        )
        INTO maximum_id;

        EXECUTE format(
            'SELECT last_value, is_called FROM %s',
            sequence_name
        )
        INTO
            sequence_last_value,
            sequence_is_called;

        IF (
            sequence_is_called
            AND sequence_last_value < maximum_id
        )
        OR (
            NOT sequence_is_called
            AND sequence_last_value <= maximum_id
        ) THEN
            EXECUTE format(
                'ALTER SEQUENCE %s RESTART WITH %s',
                sequence_name,
                maximum_id + 1
            );
        END IF;

        EXECUTE format(
            'GRANT USAGE, SELECT, UPDATE ON SEQUENCE %s TO %I',
            sequence_name,
            'ultracarApp'
        );
    END LOOP;
END;
$identity_generators$;

