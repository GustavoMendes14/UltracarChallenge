-- ============================================================
-- Known schema adjustment
--
-- Preserve existing service order values as text.
-- ============================================================

DO $service_order_type$
BEGIN
    IF EXISTS (
        SELECT 1
        FROM pg_attribute
        WHERE attrelid = 'public.reservations'::regclass
          AND attname = 'service_order_id'
          AND NOT attisdropped
          AND atttypid <> 'text'::regtype
    ) THEN
        ALTER TABLE public.reservations
            ALTER COLUMN service_order_id
            TYPE text
            USING service_order_id::text;
    END IF;
END;
$service_order_type$;

